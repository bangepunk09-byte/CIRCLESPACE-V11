export function cleanCopywritingMap(obj) {
  if (!obj || typeof obj !== "object") return {};
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === "string" && v.trim().length > 0) {
      out[k] = v;
    }
  }
  return out;
}

export function getEffectiveCopywriting(wsCopywriting, prefsCopywriting) {
  return {
    ...cleanCopywritingMap(prefsCopywriting),
    ...cleanCopywritingMap(wsCopywriting)
  };
}

export function getTranslation(key, customCopywriting = {}, fallback = "") {
  if (customCopywriting && typeof customCopywriting === "object") {
    const direct = customCopywriting[key];
    if (typeof direct === "string" && direct.trim().length > 0) {
      return direct;
    }
    const baseText = fallback || DEFAULT_COPYWRITING[key];
    if (baseText && typeof customCopywriting[baseText] === "string" && customCopywriting[baseText].trim().length > 0) {
      return customCopywriting[baseText];
    }
  }
  return fallback || DEFAULT_COPYWRITING[key] || key;
}

/**
 * Generate CSV text from current copywriting keys and custom overrides
 */
export function generateCopywritingCsv(customCopywriting = {}) {
  const headers = ["Key", "Default_Text", "Custom_Text"];
  const escapeCsv = (str) => {
    if (str === null || str === undefined) return '""';
    const s = String(str).replace(/"/g, '""');
    return `"${s}"`;
  };

  const allKeys = Array.from(
    new Set([...Object.keys(DEFAULT_COPYWRITING), ...Object.keys(customCopywriting || {})])
  );

  const rows = allKeys.map((k) => {
    const defaultVal = DEFAULT_COPYWRITING[k] ?? "";
    const customVal = customCopywriting?.[k] || "";
    return [escapeCsv(k), escapeCsv(defaultVal), escapeCsv(customVal)].join(",");
  });

  return [headers.join(","), ...rows].join("\n");
}

/**
 * Parse CSV text into a key-value dictionary of custom copywriting
 */
export function parseCopywritingCsv(csvText) {
  if (!csvText || typeof csvText !== "string") return {};
  const lines = csvText.split(/\r?\n/).filter((l) => l.trim().length > 0);
  if (lines.length <= 1) return {};

  const dict = {};

  const parseLine = (line) => {
    const values = [];
    let current = "";
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"' && (i === 0 || line[i - 1] !== "\\")) {
        if (inQuotes && line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (char === "," && !inQuotes) {
        values.push(current);
        current = "";
      } else {
        current += char;
      }
    }
    values.push(current);
    return values;
  };

  for (let i = 1; i < lines.length; i++) {
    const parts = parseLine(lines[i]);
    if (parts.length >= 2) {
      const key = parts[0].trim().replace(/^"|"$/g, "");
      let val = "";
      if (parts.length >= 3 && parts[2]?.trim()) {
        val = parts[2].trim().replace(/^"|"$/g, "");
      } else if (parts[1]?.trim() && !(key in DEFAULT_COPYWRITING)) {
        val = parts[1].trim().replace(/^"|"$/g, "");
      }
      if (key && val) {
        dict[key] = val;
      }
    }
  }

  return dict;
}
